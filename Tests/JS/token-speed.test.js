"use strict";
const assert = require("node:assert/strict");
const { emptySpeed, observeSpeed, rateFor, speedPanel } = require("../../ElectronApp/token-speed");
const base = Date.parse("2026-11-08T12:00:00Z");
const event = (s, seconds, payload) => observeSpeed(s, { timestamp: new Date(base + seconds * 1000).toISOString(), type: "event_msg", payload });
const usage = (total, last) => ({ type: "token_count", info: { total_token_usage: { output_tokens: total },
  last_token_usage: { output_tokens: last, reasoning_output_tokens: last / 2 }, last_usage_includes_reasoning: true } });
const s = emptySpeed();
event(s, 0, { type: "task_started" });
event(s, 5, usage(1000, 300));
event(s, 10, usage(1600, 600));
event(s, 10, usage(1600, 600));
assert.equal(s.output, 900, "exact output deltas; no duplicate or reasoning double counting");
assert.equal(rateFor(s, true, base + 20_000).value, 30);
assert.equal(rateFor(s, true, base + 35_000).value, 30, "keep the last reported window stable between batches");
assert.equal(rateFor(s, true, base + 40_000).value, 30, "late usage retains the previous valid rate");
assert.equal(rateFor(s, true, base + 40_000).held, true);
assert.equal(speedPanel([{state:"running",tokenSpeed:s}],"zh-CN",base+40_000).rows[0].label,"");
assert.equal(speedPanel([{state:"running",tokenSpeed:s}],"zh-CN",base+40_000).total.text,"30.0 tok/s");
const resumed = structuredClone(s);
event(resumed, 200, usage(1900,300));
assert.equal(rateFor(resumed,true,base+201000).value,10,"new actual usage replaces a carried rate");
assert.equal(rateFor(resumed,true,base+201000).held,false);
assert.equal(rateFor(JSON.parse(JSON.stringify(resumed)),true,base+1000000).value,10,"carried values reconstruct from existing bounded samples after restart");
const mixed=speedPanel([{state:"running",tokenSpeed:s},{state:"running",tokenSpeed:resumed}],"zh-CN",base+201000);
assert.equal(mixed.total.text,"40.0 tok/s","global reference includes held and fresh rates, not zeros for unreported sessions");
assert.doesNotMatch(JSON.stringify({detail:mixed.total.detail,description:mixed.total.description,rows:mixed.rows}),/沿用|≈|30秒/);
assert.equal(speedPanel([{state:"running",tokenSpeed:s}],"en",base+1000000).rows[0].label,"");
const zero=emptySpeed();event(zero,0,{type:"task_started"});event(zero,5,usage(0,0));
assert.equal(rateFor(zero,true,base+6000).value,0,"known zero is different from absent usage");
assert.equal(rateFor(zero,true,base+40000).value,0,"a known zero can be carried without inventing output");
event(zero,100,{type:"task_started"});event(zero,105,usage(0,0));
assert.equal(rateFor(zero,true,base+106000).value,0,"a valid zero report in a new turn is not a duplicate of the previous turn");
event(zero,110,{type:"task_complete",duration_ms:10000});
assert.equal(rateFor(zero,false).value,0,"an explicitly reported zero-output turn has a known zero average");
const immutable=JSON.stringify(resumed);for(let i=0;i<10000;i++)assert.equal(rateFor(resumed,true,base+1000000).held,true);
assert.equal(JSON.stringify(resumed),immutable,"repeated held reads allocate no persistent samples or cache state");
const edge=emptySpeed();event(edge,0,{type:"task_started"});event(edge,10,usage(300,300));event(edge,40,usage(600,300));
assert.equal(rateFor(edge,true,base+41000).value,10,"left edge of the window at a new report is still excluded");
const second = structuredClone(s);
const active = [{ state: "running", tokenSpeed: s }, { state: "running", tokenSpeed: second }];
assert.equal(speedPanel(active, "zh-CN", base + 20_000).total.text, "60.0 tok/s");
assert.equal(speedPanel(active, "zh-CN", base + 20_000).rows[0].status, "");
assert.equal(rateFor(s,true,base+20_000,60).value,15);
assert.equal(rateFor(s,true,base+20_000,300).value,3);
assert.equal(speedPanel(active,"zh-CN",base+20_000,300).total.text,"6.0 tok/s");
assert.doesNotMatch(speedPanel(active,"zh-CN",base+20_000,300).rows[0].description,/5分钟|实时|沿用|≈/);
event(s, 20, { type: "task_complete", duration_ms: 20000 });
assert.equal(rateFor(s, false).value, 45, "completed average includes elapsed waiting/tool time");
assert.equal(rateFor(s, true, base + 20_000).value, null, "terminal log overrides stale running classification");
assert.equal(speedPanel([{ state: "unread", tokenSpeed: s }, active[1]], "en", base + 20_000).total.text, "30.0 tok/s");
assert.equal(speedPanel([], "en").total.text, "0.0 tok/s");
assert.equal(speedPanel([{state:"running"}], "en").total.text, "— tok/s");
event(s, 100, { type: "task_started" });
assert.equal(s.output, 0);assert.equal(s.endedAt, 0);
assert.equal(rateFor(s, true, base + 101_000).value, null, "new turn does not inherit old speed");
assert.equal(rateFor(s, true, base + 101_000).held,false);
event(s, 105, usage(2000, 400));
event(s, 110, { type: "turn_aborted" });
assert.equal(rateFor(s, false).value, 40, "aborted/stopped average is historical, not live");
const stopped = structuredClone(s);
event(stopped, 111, usage(100, 50));assert.equal(rateFor(stopped,false).value,null,"late inconsistent usage cannot undercount the frozen average");
const partial = emptySpeed();
event(partial, 5, usage(1000, 300));event(partial, 20, { type: "task_complete", duration_ms: 20000 });
assert.equal(rateFor(partial, false).value, null, "a partial tail cannot pretend to know the full-turn average");
const reset = emptySpeed();event(reset,0,{type:"task_started"});event(reset,5,usage(1000,300));event(reset,10,usage(100,50));
assert.equal(rateFor(reset,true,base+11000).value,null,"counter reset never generates a negative or invented rate");
event(reset,20,{type:"task_complete",duration_ms:20000});assert.equal(rateFor(reset,false).value,null);
const missing = emptySpeed();event(missing,0,{type:"task_started"});event(missing,2,{type:"task_complete"});
assert.equal(rateFor(missing,false).value,null);
const text = speedPanel([{state:"completed",tokenSpeed:s}],"en").rows[0];assert.equal(text.label,"Average");
observeSpeed(s,null);observeSpeed(s,[]);
const guard = emptySpeed();event(guard,100,{type:"task_started"});event(guard,90,{type:"task_started"});event(guard,95,{type:"task_complete"});
assert.equal(guard.startedAt,base+100000);assert.equal(guard.endedAt,0,"late old terminal must not end a newer turn");
assert.equal(speedPanel([{state:"running",tokenSpeed:partial}],"zh-CN").rows[0].label,"");
const long = emptySpeed();event(long,0,{type:"task_started"});event(long,5,usage(300,300));event(long,100,usage(900,600));
assert.equal(rateFor(long,true,base+110000,30).value,20);
assert.equal(rateFor(long,true,base+110000,60).value,10);
assert.equal(rateFor(long,true,base+110000,300).value,3,"switching to 5m includes retained older usage, not just the old 30s window");
const incomplete=emptySpeed();event(incomplete,100,usage(900,600));
assert.equal(rateFor(incomplete,true,base+110000,300).value,null,"partial lookback cannot underreport as a full 5m sample");
const bounded=emptySpeed();event(bounded,0,{type:"task_started"});
for(let i=1;i<=4100;i++)event(bounded,i/100,usage(i,i===1?1:1));
assert.equal(bounded.samples.length,4096);
assert.equal(rateFor(bounded,true,base+42000,300).value,null,"bounded sample overflow is unknown, never a false low rate");
assert.notEqual(rateFor(bounded,true,base+42000,30).value,null);
